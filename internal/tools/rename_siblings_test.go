func TestGoRenameDiscoversOnlyUneditedIndependentDeclarations(t *testing.T) {
	root := t.TempDir()
	fixtures := map[string]string{
		"first.go":     "package sample\ntype First interface { Emit(string) string }\n",
		"second.go":    "package sample\ntype Second interface { Emit(int) int }\n",
		"other.go":     "package sample\ntype Client struct{}\nfunc (*Client) Emit(n int) int { return n }\n",
		"comments.go":  "package sample\n// Emit is only a comment.\nfunc Unrelated() {}\n",
		"malformed.go": "package sample\nfunc Emit( {\n",
		"generated.go": "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage sample\ntype Wire interface { Emit(int) int }\n",
	}
	for path, content := range fixtures {
		if err := os.WriteFile(filepath.Join(root, path), []byte(content), 0600); err != nil {
			t.Fatal(err)
		}
	}
	ws, err := workspace.Open(root)
	if err != nil {
		t.Fatal(err)
	}
	e := New(ws, config.Runtime{Workspace: root})
	first := fixtures["first.go"]
	start := strings.Index(first, "Emit")
	startColumn := start - strings.LastIndex(first[:start], "\n")
	edits := []fileEditPreview{{Path: "first.go", Edits: []editPreview{{
		Range:   core.Range{Start: core.Position{Line: 2, Column: startColumn}},
		NewText: "Send",
	}}}}
	result, err := e.findUnrenamedGoMethods(context.Background(), "Emit", edits)
	if err != nil {
		t.Fatal(err)
	}
	want := []renameSiblingCandidate{
		{Path: "other.go", SymbolPath: "Client/Emit", Kind: "receiver_method", Signature: "Emit(n int) int"},
		{Path: "second.go", SymbolPath: "Second/Emit", Kind: "interface_method", Signature: "Emit(int) int"},
		{Path: "generated.go", SymbolPath: "Wire/Emit", Kind: "interface_method", Signature: "Emit(int) int", Generated: true},
	}
	if !reflect.DeepEqual(result.Candidates, want) {
		t.Fatalf("unexpected unrenamed candidates: got %#v, want %#v", result.Candidates, want)
	}
	if result.ParseErrors != 1 {
		t.Fatalf("should record one syntactically invalid Go file, got %d", result.ParseErrors)
	}
	if result.Truncated {
		t.Fatal("should not truncate small candidates")
	}
}

func TestGoRenameSiblingSummaryDoesNotClaimSemanticIdentity(t *testing.T) {
	result := map[string]any{"applied": true}
	attachSiblingRenameWarning(result, renameSiblingScan{Candidates: []renameSiblingCandidate{{
		Path: "service.go", SymbolPath: "Independent/Emit", Kind: "interface_method",
	}}})
	if _, ok := result["unrenamed_method_candidates"]; !ok {
		t.Fatal("independent declaration was hidden from the agent")
	}
	warnings, ok := result["warnings"].([]string)
	if !ok || len(warnings) != 1 || !strings.Contains(warnings[0], "not proven dependencies") {
		t.Fatalf("failed to disclose candidate uncertainty: %#v", result)
	}
}
func TestGoRenameCandidatesPreferHandwrittenCodeWhenGeneratedStubsOverflow(t *testing.T) {
	root := t.TempDir()
	for i := 0; i < maxRenameSiblingCandidates+4; i++ {
		name := fmt.Sprintf("a_generated_%02d.go", i)
		body := fmt.Sprintf("// Code generated by tool. DO NOT EDIT.\npackage sample\ntype Wire%d interface { Emit() }\n", i)
		if err := os.WriteFile(filepath.Join(root, name), []byte(body), 0600); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.WriteFile(filepath.Join(root, "z_handwritten.go"),
		[]byte("package sample\ntype Business interface { Emit() }\n"), 0600); err != nil {
		t.Fatal(err)
	}
	ws, err := workspace.Open(root)
	if err != nil {
		t.Fatal(err)
	}
	result, err := New(ws, config.Runtime{Workspace: root}).findUnrenamedGoMethods(context.Background(), "Emit", nil)
	if err != nil {
		t.Fatal(err)
	}
	if !result.Truncated || len(result.Candidates) != maxRenameSiblingCandidates {
		t.Fatalf("should be bounded and explicitly incomplete: %#v", result)
	}
	if result.Candidates[0].Signature != "Emit()" {
		t.Fatalf("signature hint missing from plain Go method: %#v", result.Candidates[0])
	}
	if result.Candidates[0].Path != "z_handwritten.go" ||
		result.Candidates[0].SymbolPath != "Business/Emit" || result.Candidates[0].Generated {
		t.Fatalf("handwritten independent interface hidden by generated files: %#v", result.Candidates)
	}
}
